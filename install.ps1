# Set up native Windows: Alacritty and Neovim.
# bash, tmux and the main Neovim live in WSL; run ./install.sh inside WSL for those.
#
#   .\install.ps1                install packages, then link configs
#   .\install.ps1 -NoPackages    only link configs
#
# Creating symlinks needs Developer Mode (Settings > System > For developers)
# or an elevated PowerShell.
param([switch]$NoPackages)

$ErrorActionPreference = 'Stop'
$Dotfiles = $PSScriptRoot
$Backup = Join-Path $HOME (".dotfiles-backup\" + (Get-Date -Format 'yyyyMMdd-HHmmss'))

function Info($msg) { Write-Host "==> $msg" -ForegroundColor Blue }

# --- Packages ---------------------------------------------------------------
if (-not $NoPackages) {
    if (Get-Command winget -ErrorAction SilentlyContinue) {
        Info 'Installing packages with winget'
        foreach ($id in 'Alacritty.Alacritty', 'Neovim.Neovim', 'Git.Git', 'DEVCOM.JetBrainsMonoNerdFont') {
            winget install --id $id --exact --silent --accept-package-agreements --accept-source-agreements
            if ($LASTEXITCODE -ne 0) { Write-Warning "winget could not install $id (already installed, or install it by hand)" }
        }
    } else {
        Write-Warning 'winget not found; install Alacritty, Neovim and JetBrainsMono Nerd Font by hand'
    }
}

# --- Helpers ----------------------------------------------------------------
function Backup-Item($path) {
    New-Item -ItemType Directory -Force -Path $Backup | Out-Null
    $dest = Join-Path $Backup (Split-Path $path -Leaf)
    Move-Item -Path $path -Destination $dest
    Write-Host "  backup   $path -> $dest"
}

function Link-Item($source, $target) {
    $existing = Get-Item -LiteralPath $target -Force -ErrorAction SilentlyContinue
    if ($existing) {
        if ($existing.LinkType -and ($existing.Target -contains $source)) {
            Write-Host "  ok       $target"
            return
        }
        Backup-Item $target
    }
    New-Item -ItemType Directory -Force -Path (Split-Path $target -Parent) | Out-Null
    try {
        New-Item -ItemType SymbolicLink -Path $target -Target $source | Out-Null
    } catch {
        throw "Could not create a symlink at $target. Turn on Developer Mode or run PowerShell as Administrator, then re-run."
    }
    Write-Host "  linked   $target -> $source"
}

# --- Neovim -----------------------------------------------------------------
Info 'Linking configs'
Link-Item (Join-Path $Dotfiles 'nvim') (Join-Path $env:LOCALAPPDATA 'nvim')

# --- Alacritty --------------------------------------------------------------
# A small generated file that imports the shared config plus the Windows
# overrides from this repo, so both stay editable in one place.
$alacrittyDir = Join-Path $env:APPDATA 'alacritty'
$alacrittyFile = Join-Path $alacrittyDir 'alacritty.toml'
$shared = (Join-Path $Dotfiles 'alacritty\alacritty.toml') -replace '\\', '/'
$windows = (Join-Path $Dotfiles 'alacritty\windows.toml') -replace '\\', '/'
$content = @"
# Generated by dotfiles/install.ps1 - edit the imported files instead.
[general]
import = [
    "$shared",
    "$windows",
]
"@

New-Item -ItemType Directory -Force -Path $alacrittyDir | Out-Null
$current = if (Test-Path -LiteralPath $alacrittyFile) { Get-Content -LiteralPath $alacrittyFile -Raw } else { $null }
if ($current -and ($current.Trim() -eq $content.Trim())) {
    Write-Host "  ok       $alacrittyFile"
} else {
    if ($null -ne $current) { Backup-Item $alacrittyFile }
    Set-Content -LiteralPath $alacrittyFile -Value $content -Encoding utf8
    Write-Host "  wrote    $alacrittyFile"
}

Info 'Done.'
if (Test-Path $Backup) { Write-Host "Previous files were moved to $Backup" }
Write-Host 'Restart Alacritty. Then run ./install.sh inside WSL for bash, tmux and Neovim.'
